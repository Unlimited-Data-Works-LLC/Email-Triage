""" — `SELECT * FROM` over-fetch ratchet pin.

`SELECT * FROM <table>` in a HIPAA-class system returns EVERY column,
which risks unintentional PHI over-fetch: if a future migration adds
a PHI column to a table, EVERY existing `SELECT *` reader silently
starts fetching that column — the exposure surface grows without
any code review touching the reader. Explicit column-projection
(`SELECT col_a, col_b FROM …`) forces a code change at the reader
when a PHI column is added.

This pin is a RATCHET: the 51 pre-#140 pairs `(rel, enclosing_fn)`
at 2026-07-11 baseline are grandfathered; NEW `SELECT * FROM` in an
`(rel, fn)` NOT in baseline fails CI. As sites migrate to explicit
column-projection, baseline SHRINKS via `test_baseline_never_grows`.

Enumeration: any Python `Constant` string containing the pattern
`SELECT * FROM` (case-insensitive). Bounded regex — includes string
concatenation of composed SQL fragments if the `SELECT * FROM` chunk
lives inside a Constant literal.

Prime Directive #6: routes through `_pin_harness`. Name-anchored per
 R38 discipline (line-drift-resistant).

Grounding: 2026-07-11 broader-hunt AST detected 51 unique
`(rel, enclosing_fn)` pairs matching the pattern in
`src/email_triage/**/*.py`.
"""
