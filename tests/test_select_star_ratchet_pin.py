def _enclosing_fn(node: ast.AST, tree: ast.Module) -> str:
    best_name = "<module>"
    best_start = -1
    for c in ast.walk(tree):
        if not isinstance(c, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        c_start = c.lineno
        c_end = getattr(c, "end_lineno", c_start) or c_start
        if c_start <= node.lineno <= c_end and c_start > best_start:
            best_name = c.name
            best_start = c_start
    return best_name


def _collect_offenders() -> set[tuple[str, str]]:
    out: set[tuple[str, str]] = set()
    for path in iter_src_files():
        rel = relpath(path)
        tree = parse_module(path)
        if not isinstance(tree, ast.Module):
            continue
        for node in ast.walk(tree):
            if not (isinstance(node, ast.Constant)
                    and isinstance(node.value, str)):
                continue
            if _SELECT_STAR_RE.search(node.value):
                fn = _enclosing_fn(node, tree)
                out.add((rel, fn))
    return out


def test_no_new_select_star_outside_baseline():
    """Ban NEW `SELECT * FROM <table>` outside the 2026-07-11
    baseline of 51 `(rel, fn)` pairs. Explicit column-projection
    (`SELECT col_a, col_b, … FROM …`) forces future PHI-column
    additions to touch the reader in code review."""
    fresh = _collect_offenders() - _BASELINE_SELECT_STAR
    assert not fresh, (
        " SELECT-* ratchet: NEW `SELECT * FROM <table>` in a "
        "(rel, fn) pair NOT in baseline. Explicit column-projection "
        "prevents a future PHI-column migration from silently "
        "widening exposure at unchanged readers. If the wildcard "
        "is genuinely needed (schema-agnostic dump / admin export), "
        "add `(rel, enclosing_fn)` to `_BASELINE_SELECT_STAR` with a "
        "justification comment.\n\n"
        + "\n".join(f"  {rel}::{fn}" for rel, fn in sorted(fresh))
    )


def test_baseline_never_grows():
    """Strict-shrink: baseline entries whose (rel, fn) no longer
    contains `SELECT * FROM` must be pruned so the ratchet ratchets."""
    live = _collect_offenders()
    stale = _BASELINE_SELECT_STAR - live
    assert not stale, (
        " SELECT-* ratchet: baseline shrunk — prune the following "
        "(rel, fn) pairs from `_BASELINE_SELECT_STAR` (their SELECT-* "
        "has been removed):\n\n"
        + "\n".join(f"  {rel}::{fn}" for rel, fn in sorted(stale))
    )
