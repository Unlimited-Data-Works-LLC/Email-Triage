def _is_silent_swallow(node: ast.ExceptHandler) -> bool:
    """True if `node.body == [Pass]` OR `node.body == [Return None]`."""
    if len(node.body) != 1:
        return False
    s = node.body[0]
    if isinstance(s, ast.Pass):
        return True
    if isinstance(s, ast.Return) and s.value is None:
        return True
    return False


def _enclosing_fn(node: ast.AST, tree: ast.Module) -> str:
    best_name = "<module>"
    best_start = -1
    for c in ast.walk(tree):
        if not isinstance(c, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        c_start = c.lineno
        c_end = getattr(c, "end_lineno", c_start) or c_start
        if c_start <= node.lineno <= c_end and c_start > best_start:
            best_name = c.name
            best_start = c_start
    return best_name


def _collect_offenders() -> set[tuple[str, str]]:
    """Return the set of `(rel, enclosing_fn)` pairs that contain at
    least one silent-swallow at HEAD."""
    out: set[tuple[str, str]] = set()
    for path in iter_src_files():
        rel = relpath(path)
        tree = parse_module(path)
        if not isinstance(tree, ast.Module):
            continue
        for node in ast.walk(tree):
            if not isinstance(node, ast.ExceptHandler):
                continue
            if not _is_silent_swallow(node):
                continue
            fn = _enclosing_fn(node, tree)
            out.add((rel, fn))
    return out


def test_no_new_silent_swallow_outside_baseline():
    """Ban NEW silent-swallow except handlers outside the 2026-07-11
    baseline of 193 (rel, fn) pairs. A new silent-swallow needs a
    conscious call — either log-and-continue, log-and-raise, or add
    to the baseline with a justification."""
    fresh = _collect_offenders() - _BASELINE_SWALLOW
    assert not fresh, (
        "#139 silent-swallow ratchet: NEW `except X: pass` or "
        "`except X: return None` in a (rel, fn) pair NOT in the "
        "baseline. Silent-swallowing an exception can mask HIPAA-"
        "adjacent failures on compliance-relevant paths. Fix by "
        "adding a log call at minimum, or if the swallow is truly "
        "best-effort, add `(rel, enclosing_fn)` to `_BASELINE_SWALLOW` "
        "with a justification comment.\n\n"
        + "\n".join(f"  {rel}::{fn}" for rel, fn in sorted(fresh))
    )


def test_baseline_never_grows():
    """Strict-shrink: baseline entries whose (rel, fn) no longer
    contains a silent-swallow (site refactored to log-and-raise, etc.)
    MUST be removed from the baseline to keep the ratchet honest."""
    live = _collect_offenders()
    stale = _BASELINE_SWALLOW - live
    assert not stale, (
        "#139 silent-swallow ratchet: baseline shrunk — prune the "
        "following (rel, fn) pairs from `_BASELINE_SWALLOW` (their "
        "silent-swallow has been removed):\n\n"
        + "\n".join(f"  {rel}::{fn}" for rel, fn in sorted(stale))
    )
